def system_default():
    return "zh" if QLocale.system().name().lower().startswith("zh") else "en"


def set_lang(lang):
    global _lang
    _lang = lang if lang in LANGS else "en"


def lang():
    return _lang


def tr(key, **kw):
    v = S[key][_lang]
    if isinstance(v, list):
        return v
    return v.format(**kw) if kw else v
